"""Cut the roommates voice-over (ElevenLabs, Liam) into its phrases and place each on its shot.

Reads public/roommates/voiceover-source.mp3 and writes:
  public/roommates/voiceover.wav  – the re-timed VO track (45 s)
  src/roommates/voTimeline.ts     – each phrase's position and caption text
                                    (*word* = highlighted keyword in the captions)
Cut points sit in the pauses found with silencedetect. Run:
  python3 scripts/place_roommates_voiceover.py
"""
import json
import os
import subprocess

ROOT = os.path.join(os.path.dirname(__file__), "..")
SRC = os.path.join(ROOT, "public", "roommates", "voiceover-source.mp3")
OUT = os.path.join(ROOT, "public", "roommates", "voiceover.wav")
TS = os.path.join(ROOT, "src", "roommates", "voTimeline.ts")
FILM = 45.0

# (source start, source end, film position, caption text)
LINES = [
    (0.00, 3.27, 0.10, "This is what happens when *four* *roommates* share *one* *kitchen.*"),
    (3.42, 5.48, 3.40, "The *dishes* pile up for days…"),
    (5.70, 7.92, 5.45, "shared spaces become *nobody's* *job…*"),
    (8.06, 10.51, 7.62, "and every chore turns into an *argument.*"),
    (10.68, 11.58, 10.05, "The paper *rota?*"),
    (11.70, 13.12, 10.95, "*Forgotten* by week two."),
    (13.39, 15.34, 12.80, "So they tried *Plainweek* *Family* *Mode.*"),
    (15.55, 16.65, 15.05, "One shared *apartment.*"),
    (16.77, 18.24, 16.20, "Everyone joins with a *code.*"),
    (18.44, 20.62, 18.55, "Type “bins at Sam every *Tuesday*”…"),
    (20.77, 22.04, 20.75, "and chores *take* *turns.*"),
    (22.20, 24.00, 22.15, "One tap plans the whole *week.*"),
    (24.15, 24.71, 24.00, "*Fairly.*"),
    (24.96, 25.41, 25.60, "Done?"),
    (25.53, 26.40, 26.10, "Snap a *photo.*"),
    (26.60, 27.15, 27.10, "Forgot?"),
    (27.29, 28.10, 27.75, "Get a *nudge.*"),
    (28.31, 30.39, 29.05, "The shopping list sorts itself by *aisle.*"),
    (30.53, 31.94, 32.45, "Everyone knows who's *going…*"),
    (32.00, 33.06, 33.90, "and who's *driving.*"),
    (33.24, 35.11, 35.60, "And nobody can claim they did *more.*"),
    (35.32, 37.29, 37.90, "Tick chores off right from your *Home* *Screen.*"),
    (37.43, 39.32, 40.25, "Now the apartment *stays* *clean.*"),
    (39.53, 40.79, 42.18, "*Plainweek* *Family* *Mode.*"),
    (40.87, 42.34, 43.48, "*Coming* *soon* to the App Store."),
]

# never let a phrase start before the previous one has finished
placed, prev_end = [], 0.0
for a, b, at, text in LINES:
    at = max(at, prev_end + 0.06)
    placed.append((a, b, round(at, 2), text))
    prev_end = at + b - a
LINES = placed

parts, labels = [], []
for i, (a, b, at, _) in enumerate(LINES):
    d = b - a
    ms = int(round(at * 1000))
    parts.append(f"[0:a]atrim={a}:{b},asetpts=PTS-STARTPTS,afade=t=in:d=0.02,afade=t=out:st={d - 0.05:.3f}:d=0.05,adelay={ms}|{ms}[v{i}]")
    labels.append(f"[v{i}]")
graph = ";".join(parts) + ";" + "".join(labels) + (
    f"amix=inputs={len(labels)}:normalize=0:duration=longest,highpass=f=80,"
    "acompressor=threshold=-20dB:ratio=2.5:attack=8:release=120,"
    f"apad=whole_dur={FILM},atrim=0:{FILM},aresample=48000,pan=stereo|c0=c0|c1=c0[out]"
)
subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", SRC, "-filter_complex", graph, "-map", "[out]", OUT], check=True)

for (a, b, at, _), (a2, b2, at2, _) in zip(LINES, LINES[1:]):
    assert at + b - a <= at2 + 0.001, f"overlap before {at2}"
assert LINES[-1][2] + LINES[-1][1] - LINES[-1][0] <= FILM

with open(TS, "w") as f:
    f.write("// Generated by scripts/place_roommates_voiceover.py: each VO phrase in the film (seconds).\n")
    f.write("// *word* marks a highlighted keyword in the captions.\n")
    f.write("export const VO_LINES: {from: number; to: number; text: string}[] = [\n")
    for a, b, at, text in LINES:
        f.write(f"  {{from: {at:.2f}, to: {at + b - a:.2f}, text: {json.dumps(text, ensure_ascii=False)}}},\n")
    f.write("];\n")
print(f"wrote {OUT}; last phrase ends at {LINES[-1][2] + LINES[-1][1] - LINES[-1][0]:.2f}s")
