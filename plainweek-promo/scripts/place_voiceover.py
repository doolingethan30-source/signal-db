"""Cut the ElevenLabs voice-over into its lines and place each one on its shot.

Reads public/launch/voiceover-source.mp3 and writes:
  public/launch/voiceover.wav    – the re-timed VO track (film length)
  src/launch/voTimeline.ts       – where each line sits, used to duck the music

Run: python3 scripts/place_voiceover.py
"""
import json
import os
import subprocess

ROOT = os.path.join(os.path.dirname(__file__), "..")
SRC = os.path.join(ROOT, "public", "launch", "voiceover-source.mp3")
OUT = os.path.join(ROOT, "public", "launch", "voiceover.wav")
TS = os.path.join(ROOT, "src", "launch", "voTimeline.ts")
FILM = 35.0

# (source start, source end, film position, line). Source cut points sit in the
# pauses found with silencedetect; film positions line up with each shot.
LINES = [
    (0.00, 2.30, 0.40, "Your week shouldn't feel this loud."),
    (2.62, 6.30, 4.40, "Meet Plainweek. Your whole week, in one calm view."),
    (6.50, 8.85, 8.55, "Just type it. Plainweek knows what you mean."),
    (9.10, 10.98, 11.95, "Change of plans? Just drag it."),
    (11.20, 13.95, 14.85, "AI fits your tasks around your meetings."),
    (14.18, 16.75, 18.05, "Day shifted? Re-plan it in one tap."),
    (16.90, 19.12, 20.95, "Tick things off, right from your Home Screen."),
    (19.34, 19.97, 24.30, "Light."),
    (20.15, 20.74, 25.05, "Dark."),
    (20.91, 21.62, 26.15, "Glass."),
    (21.85, 22.62, 27.62, "Plainweek."),
    (22.77, 24.38, 28.50, "Spend less time planning."),
    (24.44, 26.30, 30.12, "More time doing what matters."),
]

parts = []
labels = []
for i, (a, b, at, _) in enumerate(LINES):
    d = b - a
    ms = int(round(at * 1000))
    parts.append(
        f"[0:a]atrim={a}:{b},asetpts=PTS-STARTPTS,"
        f"afade=t=in:d=0.02,afade=t=out:st={d - 0.06:.3f}:d=0.06,"
        f"adelay={ms}|{ms}[v{i}]"
    )
    labels.append(f"[v{i}]")
graph = ";".join(parts) + ";" + "".join(labels) + (
    f"amix=inputs={len(labels)}:normalize=0:duration=longest,"
    f"highpass=f=80,acompressor=threshold=-20dB:ratio=2.5:attack=8:release=120,"
    f"apad=whole_dur={FILM},atrim=0:{FILM},aresample=48000,pan=stereo|c0=c0|c1=c0[out]"
)
subprocess.run(
    ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", SRC, "-filter_complex", graph, "-map", "[out]", OUT],
    check=True,
)

with open(TS, "w") as f:
    f.write("// Generated by scripts/place_voiceover.py: where each VO line sits in the film (seconds).\n")
    f.write("export const VO_LINES: {from: number; to: number; text: string}[] = [\n")
    for a, b, at, text in LINES:
        f.write(f"  {{from: {at:.2f}, to: {at + b - a:.2f}, text: {json.dumps(text)}}},\n")
    f.write("];\n")
print(f"wrote {OUT} and {TS}; last line ends at {LINES[-1][2] + LINES[-1][1] - LINES[-1][0]:.2f}s")
