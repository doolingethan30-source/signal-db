"""Cut the Family Mode voice-over into its lines and place each one on its shot.

Reads public/family/voiceover-source.mp3 (ElevenLabs) and writes:
  public/family/voiceover.wav   – the re-timed VO track (30 s)
  src/family/voTimeline.ts      – where each line sits, used to duck the music

Cut points sit in the pauses found with silencedetect. Run:
  python3 scripts/place_family_voiceover.py
"""
import json
import os
import subprocess

ROOT = os.path.join(os.path.dirname(__file__), "..")
SRC = os.path.join(ROOT, "public", "family", "voiceover-source.mp3")
OUT = os.path.join(ROOT, "public", "family", "voiceover.wav")
TS = os.path.join(ROOT, "src", "family", "voTimeline.ts")
FILM = 30.0

# (source start, source end, film position, line)
LINES = [
    (0.00, 1.36, 0.90, "Meet Family Mode."),  # as the title appears
    (1.70, 4.16, 2.40, "One shared home… for the whole family."),
    (4.48, 6.26, 5.20, "Forgotten chores."),
    (6.30, 7.12, 7.08, "Lists everywhere."),
    (7.34, 8.50, 8.15, "And one parent…"),
    (8.66, 9.58, 9.42, "holding it all."),
    (9.84, 11.92, 10.50, "Now, assign chores in a tap."),  # the groove arrives
    (12.16, 14.40, 13.05, "Kids tick them off… and earn stars."),  # stars fly at ~14.5 s
    (14.64, 17.02, 16.20, "They ask. You approve. Done."),  # approve tap ~17.7 s
    (17.30, 20.80, 19.15, "Shared lists. One calendar. Everyone in sync."),
    (20.98, 24.04, 23.35, "One home. One plan. A happier family."),
    (24.30, 26.90, 26.70, "Discover Family Mode, with Plainweek Pro."),
]

parts, labels = [], []
for i, (a, b, at, _) in enumerate(LINES):
    d = b - a
    ms = int(round(at * 1000))
    parts.append(
        f"[0:a]atrim={a}:{b},asetpts=PTS-STARTPTS,"
        f"afade=t=in:d=0.02,afade=t=out:st={d - 0.06:.3f}:d=0.06,adelay={ms}|{ms}[v{i}]"
    )
    labels.append(f"[v{i}]")
graph = ";".join(parts) + ";" + "".join(labels) + (
    f"amix=inputs={len(labels)}:normalize=0:duration=longest,"
    "highpass=f=80,acompressor=threshold=-20dB:ratio=2.5:attack=8:release=120,"
    f"apad=whole_dur={FILM},atrim=0:{FILM},aresample=48000,pan=stereo|c0=c0|c1=c0[out]"
)
subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", SRC, "-filter_complex", graph, "-map", "[out]", OUT], check=True)

with open(TS, "w") as f:
    f.write("// Generated by scripts/place_family_voiceover.py: where each VO line sits in the film (seconds).\n")
    f.write("export const VO_LINES: {from: number; to: number; text: string}[] = [\n")
    for a, b, at, text in LINES:
        f.write(f"  {{from: {at:.2f}, to: {at + b - a:.2f}, text: {json.dumps(text, ensure_ascii=False)}}},\n")
    f.write("];\n")
for (a, b, at, _), (a2, b2, at2, _) in zip(LINES, LINES[1:]):
    assert at + b - a <= at2, f"overlap before {at2}"
print(f"wrote {OUT}; last line ends at {LINES[-1][2] + LINES[-1][1] - LINES[-1][0]:.2f}s")
